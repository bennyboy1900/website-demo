export const LANDMARKS = [
  ...MUENSTER, ...NRW, ...BERLIN, ...NORDEN, ...SUEDEN, ...OSTEN,
];

/** Reihenfolge für die Rand-Pfeile: nach Stadt gruppiert, Münster zuerst. */
export const TOUR_ORDER = (() => {
  const byCity = new Map();
  for (const l of LANDMARKS) {
    if (!byCity.has(l.city)) byCity.set(l.city, []);
    byCity.get(l.city).push(l);
  }
  const cities = [...byCity.keys()].sort((a, b) => {
    if (a === 'Münster') return -1;
    if (b === 'Münster') return 1;
    return byCity.get(b).length - byCity.get(a).length || a.localeCompare(b, 'de');
  });
  return cities.flatMap((c) => byCity.get(c));
})();
